from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field
from datetime import datetime


class VoiceCatalogRequest(BaseModel):
    product_id: str
    voice_transcript: Optional[str] = None
    language_code: Optional[str] = "hi-IN"


class CatalogAutoGeneratedMetadata(BaseModel):
    title: str
    description: str
    craft_category: str
    artisan_name: Optional[str] = None
    artisan_phone: Optional[str] = None
    artisan_dialect: Optional[str] = None
    material: Optional[str] = None
    gi_tag_status: str
    weave_technique: str
    estimated_days: float
    seo_tags: List[str] = Field(default_factory=list)


class VoiceCatalogResponse(BaseModel):
    product_id: str
    transcript_regional: str
    transcript_english: str
    metadata: CatalogAutoGeneratedMetadata
    status: str


class InventoryItemResponse(BaseModel):
    product_id: str
    title: str
    craft_category: str
    status: str
    final_price: Optional[float] = None
    passport_hash: Optional[str] = None
    enhanced_image_url: Optional[str] = None
    published_channels: List[str] = Field(default_factory=list)
    created_at: Optional[datetime] = None


class InventoryListResponse(BaseModel):
    total_items: int
    active_listings_count: int
    drafts_count: int
    inventory: List[InventoryItemResponse]


class DraftItem(BaseModel):
    local_draft_id: str
    product_title: Optional[str] = None
    craft_category: Optional[str] = "handloom"
    raw_cost: Optional[float] = 0.0
    labor_days: Optional[float] = 1.0
    dialect: Optional[str] = "bhojpuri"


class DraftSyncRequest(BaseModel):
    artisan_id: str
    drafts: List[DraftItem]


class DraftSyncResponse(BaseModel):
    synced_count: int
    synced_draft_ids: List[str]
    status: str = "success"
    message: str = "Offline drafts successfully synchronized with backend."
