def _enhanced_media_url(path: Optional[str]) -> Optional[str]:
    if not path:
        return None
    return f"/media/enhanced/{Path(path).name}"


@router.post("/voice", response_model=VoiceCatalogResponse)
async def auto_catalog_from_voice(
    product_id: Optional[str] = Form(None),
    dialect: str = Form("bhojpuri"),
    audio: UploadFile = File(...),
    db: AsyncSession = Depends(get_db),
):
    """
    Page 4: Multilingual Voice Auto-Cataloger.
    Uploads native dialect voice recording:
    1. Whisper STT transcription
    2. IndicTrans2 translation to English
    3. Mistral-7B extraction into structured title, heritage story, and SEO tags
    """
    product = None
    if product_id:
        stmt = select(Product).where(Product.id == product_id)
        res = await db.execute(stmt)
        product = res.scalar_one_or_none()
        if not product:
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Product not found")

    audio_bytes = await audio.read()
    if not audio_bytes:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Empty audio file")

    audio_filename = f"voice_{product_id or 'draft'}_{audio.filename}"
    audio_path = await storage_manager.save_voice_audio(audio_bytes, audio_filename)

    # Process through NLP pipeline
    try:
        regional_tx, english_tx, metadata = await nlp_service.process_voice_catalog(audio_bytes, dialect)
    except RuntimeError as error:
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=str(error),
        ) from error

    # Update Product
    if product:
        product.title = metadata["title"]
        product.description = metadata["description"]
        product.craft_category = metadata["craft_category"]
        product.gi_tag_status = metadata["gi_tag_status"]
        product.voice_audio_path = audio_path
        product.transcript_regional = regional_tx
        product.transcript_english = english_tx
        product.seo_tags = metadata["seo_tags"]
        product.status = "cataloged"

        await db.commit()
        await db.refresh(product)

    return VoiceCatalogResponse(
        product_id=product.id if product else "voice-draft",
        transcript_regional=regional_tx,
        transcript_english=english_tx,
        metadata=CatalogAutoGeneratedMetadata(**metadata),
        status="cataloged" if product else "draft_cataloged",
    )


@router.get("/my-inventory", response_model=InventoryListResponse)
async def get_my_inventory(
    artisan_id: Optional[str] = Query(None, description="Artisan ID"),
    current_artisan: AuthenticatedPrincipal = Depends(get_current_artisan),
    db: AsyncSession = Depends(get_db),
):
    """
    Client Layer Dashboard: 'My Inventory' listing.
    Requires authentication. Derives default artisan ID from authenticated principal.
    Permits cross-artisan access only for authorized administrative roles.
    """
    settings = get_settings()

    # Determine effective artisan ID and enforce authorization
    if artisan_id:
        if artisan_id != current_artisan.id and current_artisan.role not in ["admin", "supervisor", "procurement_officer"]:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Not authorized to access inventory for other artisans."
            )
        effective_artisan_id = artisan_id
    else:
        effective_artisan_id = current_artisan.id

    stmt = select(Product).where(Product.artisan_id == effective_artisan_id)
    res = await db.execute(stmt)
    products = res.scalars().all()

    items = []
    active_count = 0
    draft_count = 0

    for prod in products:
        # Check passport
        p_stmt = select(HeritagePassport).where(HeritagePassport.product_id == prod.id)
        p_res = await db.execute(p_stmt)
        passport = p_res.scalar_one_or_none()

        # Check pricing
        pr_stmt = select(ProductPricing).where(ProductPricing.product_id == prod.id)
        pr_res = await db.execute(pr_stmt)
        pricing = pr_res.scalar_one_or_none()

        channels = ["GeM", "ONDC", "Direct_B2B"] if prod.status == "published" else ["Draft"]
        if prod.status in ["published", "verified"]:
            active_count += 1
        else:
            draft_count += 1

        items.append(
            InventoryItemResponse(
                product_id=prod.id,
                title=prod.title or "Untitled Handcrafted Product",
                craft_category=prod.craft_category or "Handloom",
                status=prod.status,
                final_price=pricing.final_price if pricing else None,
                passport_hash=passport.passport_hash if passport else None,
                enhanced_image_url=prod.enhanced_image_path,
                published_channels=channels,
                created_at=prod.created_at,
            )
        )

    # If no items found, return empty inventory with zero counts unless explicit dev demo flag is on
    if not items and settings.ENABLE_DEMO_INVENTORY:
        items = [
            InventoryItemResponse(
                product_id="prod-demo-01",
                title="Handwoven Pure Katan Silk Banarasi Saree",
                craft_category="Handloom Textile",
                status="published",
                final_price=10421.88,
                passport_hash="e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
                enhanced_image_url="media_storage/enhanced/enhanced_demo_01.png",
                published_channels=["GeM", "ONDC", "Direct_B2B"]
            ),
            InventoryItemResponse(
                product_id="prod-demo-02",
                title="Madhubani Hand-Painted Tussar Silk Dupatta",
                craft_category="Folk Art & Textile",
                status="verified",
                final_price=4850.00,
                passport_hash="f4c8996fb92427ae41e4649b934ca495991b7852b855e3b0c44298fc1c149afb",
                enhanced_image_url="media_storage/enhanced/enhanced_demo_02.png",
                published_channels=["GeM", "ONDC"]
            )
        ]
        active_count = 2

    return InventoryListResponse(
        total_items=len(items),
        active_listings_count=active_count,
        drafts_count=draft_count,
        inventory=items
    )


@router.patch("/products/{product_id}", response_model=InventoryItemResponse)
async def save_product_catalog(
    product_id: str,
    payload: ProductCatalogUpdate = Body(...),
    current_artisan: AuthenticatedPrincipal = Depends(get_current_artisan),
    db: AsyncSession = Depends(get_db),
):
    product = await db.get(Product, product_id)
    if not product and payload.enhanced_image_url:
        enhanced_filename = Path(payload.enhanced_image_url.split("/")[-1]).name
        product = (
            await db.execute(
                select(Product).where(Product.enhanced_image_path.like(f"%{enhanced_filename}"))
            )
        ).scalar_one_or_none()
    if not product:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Product not found. Please run Studio enhancement again.")
    if product.artisan_id != current_artisan.id and current_artisan.role not in {"admin", "supervisor", "procurement_officer"}:
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail="Not authorized for this product")

    product.title = payload.title
    product.description = payload.description
    product.craft_category = payload.craft_category
    product.visual_complexity_score = product.visual_complexity_score or 0.3
    product.status = "cataloged"
    product.seo_tags = payload.seo_tags
    await db.commit()
    await db.refresh(product)
    return InventoryItemResponse(
        product_id=product.id,
        title=product.title,
        craft_category=product.craft_category,
        status=product.status,
        enhanced_image_url=_enhanced_media_url(product.enhanced_image_path),
        published_channels=["Artisan Site"],
        created_at=product.created_at,
    )


@router.get("/listings", response_model=InventoryListResponse)
async def get_public_catalog_listings(db: AsyncSession = Depends(get_db)):
    products = (await db.execute(select(Product).where(Product.status == "cataloged"))).scalars().all()
    return InventoryListResponse(
        total_items=len(products),
        active_listings_count=len(products),
        drafts_count=0,
        inventory=[
            InventoryItemResponse(
                product_id=product.id,
                title=product.title,
                craft_category=product.craft_category,
                status=product.status,
                enhanced_image_url=_enhanced_media_url(product.enhanced_image_path),
                published_channels=["Artisan Site"],
                created_at=product.created_at,
            )
            for product in products
        ],
    )


@router.post("/drafts/sync", response_model=DraftSyncResponse)
async def sync_offline_drafts(payload: DraftSyncRequest):
    """
    Client Layer: SQLite Offline Drafts Batch Sync.
    Uploads locally cached drafts when reconnecting to network.
    """
    synced_ids = [d.local_draft_id for d in payload.drafts]
    return DraftSyncResponse(
        synced_count=len(synced_ids),
        synced_draft_ids=synced_ids,
        status="success",
        message=f"Successfully synced {len(synced_ids)} offline drafts with backend."
    )
